// Run with: node poggio_webapp/static/visualizer/schema-core.test.mjs
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ingest } from "./schema-core.mjs";

const fixturesDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..", "..", "..", "tests", "fixtures",
);

function fixture(name) {
  return JSON.parse(readFileSync(join(fixturesDir, name), "utf8"));
}

function test(name, callback) {
  callback();
  console.log(`✓ ${name}`);
}

// The adapter-drift lock: the same synthetic section, canonicalized here and
// by pipeline/canonical.py, must be one document. The committed .canonical
// twins are generated by the Python canonicalizer, and a Python test
// (test_visualizer_static_dependencies.py) pins them against it, so a change
// on either side fails one suite or the other.
test("field capture canonicalizes exactly as the Python canonicalizer", () => {
  assert.deepEqual(
    ingest(fixture("t907-parity-fieldwall.json")),
    fixture("t907-parity-fieldwall.canonical.json"),
  );
});

test("illustrator capture canonicalizes exactly as the Python canonicalizer", () => {
  // The fixture's lower layers have null tops, so this also locks the D1
  // derivation: derived boundaries and their flags must match.
  assert.deepEqual(
    ingest(fixture("t907-parity-illustrator.json")),
    fixture("t907-parity-illustrator.canonical.json"),
  );
});

test("a canonical document passes through untouched, same object", () => {
  const document = fixture("t907-parity-fieldwall.canonical.json");
  assert.equal(ingest(document), document);
});

test("field-wall points keep sourcePixel and uncertainty", () => {
  const result = ingest({
    faceLabel: "north",
    layers: [{
      topBoundary: [{
        xMeters: 1,
        depthMeters: 0.5,
        confidence: "human-traced",
        sourcePixel: [200, 250],
      }],
    }],
  });

  assert.deepEqual(result.faces[0].layers[0].topBoundary[0], {
    xMeters: 1,
    depthMeters: 0.5,
    confidence: "human-traced",
    uncertaintyCm: null,
    sourcePixel: [200, 250],
  });
});

test("ingest does not invent sourcePixel", () => {
  const result = ingest({
    faceLabel: "north",
    layers: [{
      topBoundary: [{ xMeters: 1, depthMeters: 0.5 }],
      bottomBoundary: [{ xMeters: 1, depthMeters: 1 }],
      featuresInLayer: [{
        feature: "stone",
        shapePoints: [{ xMeters: 2, depthMeters: 0.5 }],
      }],
    }],
  });
  const layer = result.faces[0].layers[0];
  const points = [
    ...layer.topBoundary,
    ...layer.bottomBoundary,
    ...layer.features[0].shapePoints,
  ];

  points.forEach(point => {
    assert.equal(
      Object.prototype.hasOwnProperty.call(point, "sourcePixel"),
      false,
    );
  });
});

test("legacy point keys adapt regardless of which pair a file uses", () => {
  const result = ingest({
    faceLabel: "north",
    layers: [{
      topBoundary: [{
        xCoordinateMeters: 1.25,
        yCoordinateMeters: 0.75,
        confidence: "model",
      }],
    }],
  });

  assert.deepEqual(result.faces[0].layers[0].topBoundary[0], {
    xMeters: 1.25,
    depthMeters: 0.75,
    confidence: "model",
    uncertaintyCm: null,
  });
});

test("an old projected document keeps the display label its medium earned", () => {
  // The shape merge_extractions writes: identity in both name keys and the
  // Munsell reading already resolved into displayLabel.
  const result = ingest({
    trenchProfiles: [{
      face: "north wall",
      gridRefs: [],
      layers: [{
        layerName: "Locus 2",
        inferredMaterial: "Locus 2",
        displayLabel: "Locus 2 (10YR 3/2 very dark grayish brown)",
        topBoundary: [{ xMeters: 0, depthMeters: 0.4 }],
        bottomBoundary: [{ xMeters: 0, depthMeters: 0.8 }],
      }],
    }],
  });
  const layer = result.faces[0].layers[0];

  assert.equal(layer.surfaceId, "Locus 2");
  assert.equal(layer.displayLabel, "Locus 2 (10YR 3/2 very dark grayish brown)");
});

test("unrecognized input is returned unchanged for the pickers to reject", () => {
  const input = { pointsCsv: true };
  assert.equal(ingest(input), input);
  assert.equal(ingest(null), null);
});
